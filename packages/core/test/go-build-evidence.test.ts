import { describe, expect, it } from "vitest";
import { buildGoModules, goVendoredDirectory, isGoBuildIgnored, isGoGeneratedSource } from "../src/go-projects.js";
import { buildImportGraph } from "../src/import-graph.js";
import { rankContextFiles } from "../src/rank.js";
import type { RepoFile, RepoMap } from "../src/types.js";

const repoOf = (files: RepoFile[]): RepoMap => ({ root: "/repo", packageScripts: [], changedFiles: [], diffText: "", packageManager: "npm", diagnostics: [], files });

function file(path: string, textSample: string): RepoFile {
  return {
    path,
    extension: path.slice(path.lastIndexOf(".")),
    sizeBytes: textSample.length,
    isSource: true,
    isTest: path.endsWith("_test.go"),
    kind: path.endsWith(".go") ? "code" : "config",
    textSample
  };
}

describe("Go build evidence", () => {
  it("recognizes build-ignored programs only from the header, before the package clause", () => {
    expect(isGoBuildIgnored(file("gen/main.go", "//go:build ignore\n\npackage main\n"))).toBe(true);
    expect(isGoBuildIgnored(file("gen/old.go", "// +build ignore\n\npackage main\n"))).toBe(true);
    expect(isGoBuildIgnored(file("pkg/linux.go", "//go:build linux\n\npackage pkg\n"))).toBe(false);
    expect(isGoBuildIgnored(file("pkg/doc.go", "package pkg\n\n//go:build ignore\n"))).toBe(false);
  });

  it("recognizes Go's generated-code header and nothing looser", () => {
    expect(isGoGeneratedSource(file("api/api.pb.go", "// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage api\n"))).toBe(true);
    expect(isGoGeneratedSource(file("api/hand.go", "// This code was generated once and is now maintained by hand.\npackage api\n"))).toBe(false);
    expect(isGoGeneratedSource(file("api/late.go", "package api\n// Code generated by x. DO NOT EDIT.\n"))).toBe(false);
    expect(isGoGeneratedSource(file("api/api.pb.ts", "// Code generated by x. DO NOT EDIT.\n"))).toBe(false);
  });

  it("keeps build-ignored generators out of package import edges", () => {
    const graph = buildImportGraph([
      file("go.mod", "module example.com/app\n"),
      file("cmd/app/main.go", 'package main\n\nimport "example.com/app/store"\n\nfunc main() { store.Open() }\n'),
      file("store/store.go", "package store\n\nfunc Open() {}\n"),
      file("store/gen.go", "//go:build ignore\n\npackage main\n\nfunc main() {}\n")
    ]);
    expect([...(graph.imports.get("cmd/app/main.go") ?? [])]).toEqual(["store/store.go"]);
  });

  it("resolves only packages listed in vendor/modules.txt to the vendored directory", () => {
    const files = [
      file("go.mod", "module example.com/app\n\ngo 1.22\n"),
      file("vendor/modules.txt", "# github.com/acme/log v1.2.0\n## explicit; go 1.20\ngithub.com/acme/log\n# github.com/acme/other v0.1.0\n"),
      file("main.go", 'package main\n\nimport (\n  "github.com/acme/log"\n  "github.com/acme/other"\n)\n\nfunc main() { log.Info() }\n'),
      file("vendor/github.com/acme/log/log.go", "package log\n\nfunc Info() {}\n"),
      file("vendor/github.com/acme/other/other.go", "package other\n")
    ];
    const [module] = buildGoModules(files);
    expect(module!.vendoredPackages).toEqual(["github.com/acme/log"]);
    expect(goVendoredDirectory(module!, "github.com/acme/log")).toBe("vendor/github.com/acme/log");
    expect(goVendoredDirectory(module!, "github.com/acme/other")).toBeUndefined();
    const graph = buildImportGraph(files);
    expect([...(graph.imports.get("main.go") ?? [])]).toEqual(["vendor/github.com/acme/log/log.go"]);
  });

  it("deprioritizes generated Go code and denies it the maintained-source bonus unless the task names it", () => {
    const body = "package api\n\ntype User struct { Email string }\nfunc (u *User) GetEmail() string { return u.Email }\n";
    const header = "// Code generated by protoc-gen-go. DO NOT EDIT.\n\n";
    const task = "User email is not normalized; GetEmail returns raw Email";
    const score = (text: string, issueText = task) =>
      rankContextFiles(repoOf([file("api/user.pb.go", text)]), { issueText }).find((entry) => entry.path === "api/user.pb.go");
    const plain = score(body)!;
    const generated = score(header + body)!;
    expect(plain.reasons).toContain("task identifier is defined in maintained implementation source");
    expect(generated.reasons).not.toContain("task identifier is defined in maintained implementation source");
    expect(generated.reasons).toContain("generated Go code (DO NOT EDIT header) deprioritized; edit its generator instead");
    expect(plain.score - generated.score).toBe(20);
    const named = score(header + body, "Fix api/user.pb.go GetEmail")!;
    expect(named.reasons).not.toContain("generated Go code (DO NOT EDIT header) deprioritized; edit its generator instead");
  });
});
