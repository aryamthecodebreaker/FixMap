// Regenerates the example reports that show FixMap declining to answer.
//
//   npm run build:cli && node scripts/render-honest-examples.mjs
//
// The success examples were the only ones published, which let a reader assume
// FixMap always returns a confident ranking. These three show the opposite and
// are generated from live output so they cannot drift from actual behavior.

import { writeFile } from "node:fs/promises";
import { fileURLToPath, pathToFileURL } from "node:url";
import { dirname, join, resolve } from "node:path";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const { buildFixMapReport } = await import(
  pathToFileURL(join(repoRoot, "packages", "core", "dist", "index.js")).href
);
const { renderMarkdownReport } = await import(
  pathToFileURL(join(repoRoot, "packages", "core", "dist", "report.js")).href
);

const fixture = join(repoRoot, "examples", "tiny-auth-app");

const examples = [
  {
    file: "declines-fabricated-identifier.md",
    task: "resolveTenantScopedSessionBinding throws SessionBindingMismatch when the rotation window closes",
    heading: "Task naming symbols that do not exist"
  },
  {
    file: "declines-vague-task.md",
    task: "clean this up and make the general performance better overall",
    heading: "Task with nothing to route to"
  },
  {
    file: "declines-unmatched-terms.md",
    task: "the telemetry ingestion pipeline drops spans during backpressure",
    heading: "Task about behavior this repository does not contain"
  }
];

for (const example of examples) {
  const report = await buildFixMapReport({ repoRoot: fixture, issueText: example.task });
  const body = renderMarkdownReport(report);
  const document = [
    `<!-- Generated by scripts/render-honest-examples.mjs. Do not edit by hand. -->`,
    `# ${example.heading}`,
    "",
    "```bash",
    `npx -y @aryam/fixmap@latest plan --repo examples/tiny-auth-app \\`,
    `  --issue ${JSON.stringify(example.task)}`,
    "```",
    "",
    body.trim(),
    ""
  ].join("\n");
  const output = join(repoRoot, "examples", "reports", example.file);
  await writeFile(output, document, "utf8");
  console.log(output);
}
