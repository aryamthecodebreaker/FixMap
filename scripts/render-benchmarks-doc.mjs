#!/usr/bin/env node
// Keeps the "Current recorded results" table in docs/BENCHMARKS.md generated from the recorded
// baseline-results.json files, so the document cannot drift from the data again.
//   node scripts/render-benchmarks-doc.mjs           rewrite the table
//   node scripts/render-benchmarks-doc.mjs --check   fail when the table is out of date
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const docPath = join(root, "docs", "BENCHMARKS.md");
const START = "<!-- recorded-results:start (generated by scripts/render-benchmarks-doc.mjs; do not edit) -->";
const END = "<!-- recorded-results:end -->";

// Order and role of every ranking cohort. "Development" and "regression" cohorts shaped the
// ranker; only held-out cohorts are evidence of generalization.
const COHORTS = [
  { suite: "heldout", label: "JS/TS held-out", role: "held-out" },
  { suite: "polyglot-heldout", label: "Polyglot held-out 1 (7 languages)", role: "held-out, then development" },
  { suite: "polyglot-heldout-2", label: "Polyglot held-out 2 (7 languages)", role: "held-out" },
  { suite: "polyglot-heldout-3", label: "Polyglot held-out 3 (7 languages)", role: "held-out" },
  { suite: "external", label: "External regression", role: "regression" },
  { suite: "multilanguage-dev", label: "Multilanguage development", role: "development" },
  { suite: "polyglot-dev", label: "Polyglot development", role: "development" },
  { suite: "polyglot-validation", label: "Polyglot validation", role: "development" }
];

const percent = (rate, cases) => `${Math.round(rate * cases)}/${cases} (${(rate * 100).toFixed(1)}%)`;
const rows = [];
for (const cohort of COHORTS) {
  const result = JSON.parse(await readFile(join(root, "benchmarks", cohort.suite, "baseline-results.json"), "utf8"));
  const fixmap = result.arms.fixmap.all;
  const bm25 = result.arms["bm25:code"].all;
  const p = result.pairedVsFixmapMcnemarExact?.all?.["bm25:code"]?.top5?.pValue;
  rows.push(`| ${cohort.label} | ${cohort.role} | ${fixmap.cases} | ${percent(fixmap.top1HitRate, fixmap.cases)} | ${percent(fixmap.top3HitRate, fixmap.cases)} | ${percent(fixmap.top5HitRate, fixmap.cases)} | ${percent(bm25.top5HitRate, bm25.cases)} | ${p === undefined ? "n/a" : p} |`);
}
const table = [
  START,
  "",
  "| Cohort | Role | Cases | FixMap Top-1 | FixMap Top-3 | FixMap Top-5 | BM25 Top-5 | Top-5 McNemar p |",
  "| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: |",
  ...rows,
  "",
  "Read from each cohort's `benchmarks/<cohort>/baseline-results.json`. Only held-out cohorts measure generalization;",
  "development and regression cohorts shaped the ranker. On the largest fresh cohort FixMap is on par with",
  "BM25 over code, not significantly better (see `benchmarks/polyglot-heldout-3/README.md`).",
  "",
  END
].join("\n");

const doc = await readFile(docPath, "utf8");
const start = doc.indexOf(START);
const end = doc.indexOf(END);
if (start < 0 || end < 0) throw new Error("docs/BENCHMARKS.md is missing the recorded-results markers.");
const next = doc.slice(0, start) + table + doc.slice(end + END.length);
if (process.argv.includes("--check")) {
  if (next !== doc) {
    console.error("docs/BENCHMARKS.md recorded-results table is stale; run node scripts/render-benchmarks-doc.mjs.");
    process.exit(1);
  }
  console.log("docs/BENCHMARKS.md recorded-results table matches the recorded data.");
} else {
  await writeFile(docPath, next);
  console.log("Updated docs/BENCHMARKS.md recorded-results table.");
}
